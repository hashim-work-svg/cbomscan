// Package report provides Markdown, CSV, and tabular reporting for cbomscan findings.
package report

import (
	"bytes"
	"encoding/csv"
	"fmt"
	"strconv"
	"strings"

	"github.com/hashim-work-svg/cbomscan/internal/score"
)

// GenerateMarkdown creates an executive cryptographic risk report in Markdown.
func GenerateMarkdown(findings []score.ScoredFinding, certs []score.ScoredCertificate) string {
	var b bytes.Buffer

	criticalCount := 0
	highCount := 0
	mediumCount := 0
	lowCount := 0

	for _, f := range findings {
		switch f.Tier {
		case score.TierCritical:
			criticalCount++
		case score.TierHigh:
			highCount++
		case score.TierMedium:
			mediumCount++
		default:
			lowCount++
		}
	}
	for _, c := range certs {
		switch c.Tier {
		case score.TierCritical:
			criticalCount++
		case score.TierHigh:
			highCount++
		case score.TierMedium:
			mediumCount++
		default:
			lowCount++
		}
	}

	b.WriteString("# Cryptographic Bill of Materials (CBOM) & Risk Report\n\n")
	b.WriteString("Generated by **cbomscan** — Post-Quantum & Legacy Cryptographic Risk Scanner.\n\n")

	b.WriteString("## Executive Summary\n\n")
	b.WriteString("| Metric | Count |\n")
	b.WriteString("| :--- | :---: |\n")
	b.WriteString(fmt.Sprintf("| Total Source/Config Assets | %d |\n", len(findings)))
	b.WriteString(fmt.Sprintf("| Total X.509 Certificates | %d |\n", len(certs)))
	b.WriteString(fmt.Sprintf("| 🔴 Critical Priority (85–100) | %d |\n", criticalCount))
	b.WriteString(fmt.Sprintf("| 🟠 High Priority (60–84) | %d |\n", highCount))
	b.WriteString(fmt.Sprintf("| 🟡 Medium Priority (35–59) | %d |\n", mediumCount))
	b.WriteString(fmt.Sprintf("| 🟢 Low / Info Priority (0–34) | %d |\n\n", lowCount))

	if len(findings) > 0 {
		b.WriteString("## Source & Configuration Findings\n\n")
		b.WriteString("| Rule ID | Algorithm | Classification | Tier | Score | Location | Recommendation |\n")
		b.WriteString("| :--- | :--- | :--- | :---: | :---: | :--- | :--- |\n")
		for _, f := range findings {
			loc := fmt.Sprintf("`%s:%d`", f.Finding.FilePath, f.Finding.LineNumber)
			b.WriteString(fmt.Sprintf("| `%s` | %s | %s | **%s** | %d | %s | %s |\n",
				f.Finding.RuleID,
				f.Finding.Algorithm,
				f.Finding.Classification,
				f.Tier,
				f.Score,
				loc,
				f.Finding.Recommendation,
			))
		}
		b.WriteString("\n")
	}

	if len(certs) > 0 {
		b.WriteString("## X.509 Certificate Inventory\n\n")
		b.WriteString("| Certificate | Subject | Key Type | Bits/Curve | Expiry | Tier | Score | Classification |\n")
		b.WriteString("| :--- | :--- | :--- | :--- | :---: | :---: | :---: | :--- |\n")
		for _, c := range certs {
			expiry := fmt.Sprintf("%dd remaining", c.Analysis.DaysUntilExpiry)
			if c.Analysis.IsExpired {
				expiry = "⚠️ **EXPIRED**"
			}
			details := fmt.Sprintf("%d", c.Analysis.KeySizeBits)
			if c.Analysis.Curve != "" {
				details = c.Analysis.Curve
			}
			b.WriteString(fmt.Sprintf("| `%s` | %s | %s | %s | %s | **%s** | %d | %s |\n",
				c.Analysis.FilePath,
				c.Analysis.Subject,
				c.Analysis.KeyType,
				details,
				expiry,
				c.Tier,
				c.Score,
				c.Analysis.Classification,
			))
		}
		b.WriteString("\n")
	}

	b.WriteString("## Post-Quantum Remediation Guidance\n\n")
	b.WriteString("1. **Critical Assets (Score 85–100):** Immediately replace legacy broken ciphers (MD5, SHA-1, DES, RC4) and renew expired certificates.\n")
	b.WriteString("2. **High Assets (Score 60–84):** Transition public-key algorithms in authentication and payment pathways to NIST PQC standards (FIPS 203 ML-KEM / FIPS 204 ML-DSA).\n")
	b.WriteString("3. **Medium Assets (Score 35–59):** Track general RSA and ECC public-key instances against 2030 NIST deprecation deadlines.\n")

	return b.String()
}

// GenerateCSV creates a comma-separated values report of all findings and certificates.
func GenerateCSV(findings []score.ScoredFinding, certs []score.ScoredCertificate) ([]byte, error) {
	var buf bytes.Buffer
	writer := csv.NewWriter(&buf)

	header := []string{
		"AssetType", "Identifier", "Algorithm", "Classification", "Severity",
		"PriorityScore", "PriorityTier", "Location", "Line", "MatchedText", "Recommendation",
	}
	if err := writer.Write(header); err != nil {
		return nil, err
	}

	for _, f := range findings {
		record := []string{
			"source",
			f.Finding.RuleID,
			f.Finding.Algorithm,
			string(f.Finding.Classification),
			f.Finding.Severity,
			strconv.Itoa(f.Score),
			string(f.Tier),
			f.Finding.FilePath,
			strconv.Itoa(f.Finding.LineNumber),
			strings.ReplaceAll(f.Finding.MatchedText, "\n", " "),
			f.Finding.Recommendation,
		}
		if err := writer.Write(record); err != nil {
			return nil, err
		}
	}

	for _, c := range certs {
		record := []string{
			"certificate",
			c.Analysis.Subject,
			c.Analysis.KeyType,
			string(c.Analysis.Classification),
			"high",
			strconv.Itoa(c.Score),
			string(c.Tier),
			c.Analysis.FilePath,
			"1",
			fmt.Sprintf("KeySize=%d Curve=%s", c.Analysis.KeySizeBits, c.Analysis.Curve),
			c.Analysis.Recommendation,
		}
		if err := writer.Write(record); err != nil {
			return nil, err
		}
	}

	writer.Flush()
	return buf.Bytes(), writer.Error()
}
